using PrintLog.SlicerSettings.AnycubicSlicerNext;
using PrintLog.SlicerSettings.BambuStudio;
using PrintLog.SlicerSettings.FLSunSlicer;
using PrintLog.SlicerSettings.OrcaSlicer;
using PrintLog.SlicerSettings.PrusaSlicer;

namespace PrintLog.SlicerSettings
{
    /// <summary>
    /// Everything detection needs to know about one slicer. <paramref name="Name"/> is the short, stable name the
    /// uploader uses in telemetry event names.
    /// </summary>
    internal sealed record SlicerRegistration(
        string Name,
        Func<string, bool> Detect,
        Func<INoteTemplate> DefaultTemplate,
        Func<INoteTemplate> FullTemplate,
        Func<string?, GcodeParserBase> Create);

    /// <summary>
    /// The slicer <see cref="SlicerDetector.Detect"/> settled on, and the means to parse its G-code.
    /// </summary>
    public sealed class DetectedSlicer
    {
        private readonly SlicerRegistration registration;

        internal DetectedSlicer(SlicerRegistration registration, bool isRecognized)
        {
            this.registration = registration;
            IsRecognized = isRecognized;
        }

        /// <summary>
        /// Short, stable registry name (<c>Orca</c>, <c>Prusa</c>, <c>FLSun</c>, <c>BambuStudio</c>,
        /// <c>AnycubicSlicerNext</c>). This is not the <see cref="CuraSettingDto.Slicer"/> value a parse reports.
        /// </summary>
        public string Name => registration.Name;

        /// <summary>
        /// True when the text carried this slicer's marker. False when no marker matched and the slicer was chosen by
        /// how many of its full template's placeholders have a value, which is a best guess.
        /// </summary>
        public bool IsRecognized { get; }

        /// <summary>The slicer's built-in default note template.</summary>
        public INoteTemplate DefaultTemplate => registration.DefaultTemplate();

        /// <summary>The slicer's built-in full note template.</summary>
        public INoteTemplate FullTemplate => registration.FullTemplate();

        /// <summary>
        /// A parser for this slicer that renders <paramref name="noteTemplate"/>, or the slicer's default template
        /// when it is null or empty.
        /// </summary>
        public IGcodeParser CreateParser(string? noteTemplate) => registration.Create(noteTemplate);

        internal GcodeParserBase CreateParserBase(string? noteTemplate) => registration.Create(noteTemplate);
    }

    /// <summary>
    /// Works out which slicer wrote a piece of G-code.
    /// </summary>
    public static class SlicerDetector
    {
        /// <summary>
        /// Registry order matters: it is the detection order, and the heuristic fallback resolves ties in favour of
        /// the earlier entry (so Orca is the default when nothing matches at all).
        /// </summary>
        private static readonly SlicerRegistration[] Slicers =
        [
            new("Orca", OrcaParser.IsOrcaSlicer, () => EmbeddedNoteTemplate.Default("OrcaSlicer"), () => EmbeddedNoteTemplate.Full("OrcaSlicer"), t => new OrcaParser(t)),
            new("Prusa", PrusaParser.IsPrusaSlicer, () => EmbeddedNoteTemplate.Default("PrusaSlicer"), () => EmbeddedNoteTemplate.Full("PrusaSlicer"), t => new PrusaParser(t)),
            new("FLSun", FLSunParser.IsFLSunSlicer, () => EmbeddedNoteTemplate.Default("FLSunSlicer"), () => EmbeddedNoteTemplate.Full("FLSunSlicer"), t => new FLSunParser(t)),
            new("BambuStudio", BambuStudioParser.IsBambuStudio, () => EmbeddedNoteTemplate.Default("BambuStudio"), () => EmbeddedNoteTemplate.Full("BambuStudio"), t => new BambuStudioParser(t)),
            new("AnycubicSlicerNext", AnycubicSlicerNextParser.IsAnycubicSlicerNext, () => EmbeddedNoteTemplate.Default("AnycubicSlicerNext"), () => EmbeddedNoteTemplate.Full("AnycubicSlicerNext"), t => new AnycubicSlicerNextParser(t)),
        ];

        /// <summary>
        /// The first slicer whose marker (e.g. <c>; generated by OrcaSlicer</c>, which slicers write in the header)
        /// appears in <paramref name="gcode"/>. Without one, every slicer's full template is scored against the text
        /// and the one with the highest fraction of placeholders that have a value wins; the result then has
        /// <see cref="DetectedSlicer.IsRecognized"/> false. Never throws, and empty text falls back to OrcaSlicer.
        /// </summary>
        /// <param name="gcode">The G-code, or any part of it that holds the header and/or the settings block.</param>
        /// <param name="onTemplateMatchScored">
        /// Called once per slicer during the fallback with its registry name and the fraction (0 to 1) of its
        /// placeholders that matched. Not called when a marker matched.
        /// </param>
        public static DetectedSlicer Detect(string gcode, Action<string, double>? onTemplateMatchScored = null)
        {
            gcode = GcodeWindow.Trim(gcode);

            var recognized = Slicers.FirstOrDefault(s => s.Detect(gcode));
            return recognized != null
                ? new DetectedSlicer(recognized, isRecognized: true)
                : new DetectedSlicer(FindClosestMatch(gcode, onTemplateMatchScored), isRecognized: false);
        }

        private static SlicerRegistration FindClosestMatch(string gcode, Action<string, double>? onTemplateMatchScored)
        {
            // Parsers differ only in the separators they accept, so the gcode is indexed once per distinct separator set.
            var settingsBySeparators = new Dictionary<string, GcodeSettings>();

            return Slicers.MaxBy(slicer =>
            {
                var parser = slicer.Create(slicer.FullTemplate().getNoteTemplate());
                var separators = parser.SettingSeparators.ToString();
                if (!settingsBySeparators.TryGetValue(separators, out var settings))
                {
                    settings = GcodeSettings.Parse(gcode, separators);
                    settingsBySeparators[separators] = settings;
                }

                var (numPlaceholders, numMatches) = parser.CountTemplateMatches(settings);
                var percentMatch = (double)numMatches / numPlaceholders;

                onTemplateMatchScored?.Invoke(slicer.Name, percentMatch);

                return percentMatch;
            })!;
        }
    }
}
