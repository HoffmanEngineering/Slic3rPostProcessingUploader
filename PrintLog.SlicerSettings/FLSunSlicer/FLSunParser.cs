using System.Text.RegularExpressions;

namespace PrintLog.SlicerSettings.FLSunSlicer
{
    internal partial class FLSunParser(string? noteTemplate) : GcodeParserBase(noteTemplate)
    {
        protected override string SlicerName => "FLSunSlicer";
        // Anchored: GetSlicerVersion runs it from SlicerVersionMarker to the end of that line.
        [GeneratedRegex(@"^generated by FlsunSlicer (.+) on", RegexOptions.IgnoreCase)]
        private static partial Regex VersionRegex();
        protected override Regex SlicerVersionRegex => VersionRegex();
        protected override string SlicerVersionMarker => "generated by FlsunSlicer ";
        protected override INoteTemplate CreateDefaultTemplate() => EmbeddedNoteTemplate.Default("FLSunSlicer");

        public static bool IsFLSunSlicer(string gcode)
        {
            return gcode.Contains("generated by FlsunSlicer", StringComparison.Ordinal);
        }
    }
}
