using System.Text.RegularExpressions;

namespace PrintLog.SlicerSettings.PrusaSlicer
{
    internal partial class PrusaParser(string? noteTemplate) : GcodeParserBase(noteTemplate)
    {
        protected override string SlicerName => "PrusaSlicer";
        // Anchored: GetSlicerVersion runs it from SlicerVersionMarker to the end of that line.
        [GeneratedRegex(@"^generated by PrusaSlicer (.+) on", RegexOptions.IgnoreCase)]
        private static partial Regex VersionRegex();
        protected override Regex SlicerVersionRegex => VersionRegex();
        protected override string SlicerVersionMarker => "generated by PrusaSlicer ";
        // MMU and XL exports write one "filament used" value per extruder slot, in the same shape OrcaSlicer uses.
        protected override bool SupportsMultiFilament => true;
        protected override INoteTemplate CreateDefaultTemplate() => EmbeddedNoteTemplate.Default("PrusaSlicer");

        public static bool IsPrusaSlicer(string gcode)
        {
            return gcode.Contains("generated by PrusaSlicer", StringComparison.Ordinal);
        }
    }
}
