using Slic3rPostProcessingUploader.Services;
using PrintLog.SlicerSettings;
using PrintLog.SlicerSettings.AnycubicSlicerNext;
using PrintLog.SlicerSettings.BambuStudio;
using PrintLog.SlicerSettings.FLSunSlicer;
using PrintLog.SlicerSettings.OrcaSlicer;
using PrintLog.SlicerSettings.PrusaSlicer;

namespace Slic3rPostProcessingUploaderUnitTests.Services.Parsers
{
    [TestClass]
    public class ParserFactoryTests
    {
        private StringWriter _screen = null!;
        private ConsoleOutput _output = null!;
        private TelemetryService _telemetry = null!;

        [TestInitialize]
        public void Setup()
        {
            _screen = new StringWriter();
            _output = new ConsoleOutput(_screen, null, verbose: false, unicode: true, useColor: false);
            _telemetry = new TelemetryService(disableTelemetry: true);
        }

        [TestCleanup]
        public void Cleanup() => _telemetry.Dispose();

        [TestMethod]
        public void GetParser_RecognizedSlicer_PrintsNothing()
        {
            ParserFactory.GetParser(new ArgumentParser(["--default"]), _telemetry, _output, "; generated by OrcaSlicer 2.3.0\n");

            Assert.AreEqual(string.Empty, _screen.ToString());
        }

        [TestMethod]
        public void GetParser_UnrecognizedSlicer_WarnsAboutBestMatchFallback()
        {
            ParserFactory.GetParser(new ArgumentParser(["--default"]), _telemetry, _output, "; some unknown slicer\n; layer_height = 0.2\n");

            StringAssert.StartsWith(_screen.ToString(), "  ! Slicer not recognized");
        }

        [TestMethod]
        [DataRow("; generated by OrcaSlicer 2.3.0\n", typeof(OrcaParser))]
        [DataRow("; generated by PrusaSlicer 2.9.0 on 2025-01-01\n", typeof(PrusaParser))]
        [DataRow("; generated by FlsunSlicer 1.0.0\n", typeof(FLSunParser))]
        [DataRow("; BambuStudio 1.10.0\n", typeof(BambuStudioParser))]
        [DataRow("; generated by AnycubicSlicerNext 1.0.0\n", typeof(AnycubicSlicerNextParser))]
        public void GetParser_SlicerMarker_SelectsMatchingParser(string gcode, Type expectedParser)
        {
            var parser = ParserFactory.GetParser(new ArgumentParser(["--default"]), _telemetry, _output, gcode);

            Assert.AreEqual(expectedParser, parser.GetType());
            Assert.AreEqual(string.Empty, _screen.ToString());
        }

        [TestMethod]
        public void GetParser_NoMarkerWithPrusaOnlyKeys_FallsBackToPrusaParser()
        {
            var gcode = "; some unknown slicer\n; perimeters = 3\n; fill_density = 15%\n; perimeter_generator = arachne\n; top_solid_min_thickness = 0.7\n";

            var parser = ParserFactory.GetParser(new ArgumentParser(["--default"]), _telemetry, _output, gcode);

            Assert.IsInstanceOfType<PrusaParser>(parser);
        }

        [TestMethod]
        public void GetParser_UnrecognizedSlicer_SendsAPercentMatchEventPerSlicer()
        {
            var events = new List<(string Name, Dictionary<string, object>? Properties)>();

            ParserFactory.GetParser(new ArgumentParser(["--default"]), (name, properties) => events.Add((name, properties)), _output, "; some unknown slicer\n; layer_height = 0.2\n");

            // Dashboards query these names, so renaming a registry entry is a telemetry change.
            CollectionAssert.AreEqual(
                new[] { "Template", "OrcaPercentMatch", "PrusaPercentMatch", "FLSunPercentMatch", "BambuStudioPercentMatch", "AnycubicSlicerNextPercentMatch" },
                events.Select(e => e.Name).ToArray());
            Assert.AreEqual("Default", events[0].Properties!["Template"]);
            Assert.IsTrue(events.Skip(1).All(e => e.Properties!["PercentMatch"] is double percent && percent is >= 0 and <= 1));
        }

        [TestMethod]
        public void GetParser_RecognizedSlicer_SendsOnlyTheTemplateEvent()
        {
            var events = new List<string>();

            ParserFactory.GetParser(new ArgumentParser(["--full"]), (name, _) => events.Add(name), _output, "; generated by OrcaSlicer 2.3.0\n");

            CollectionAssert.AreEqual(new[] { "Template" }, events);
        }

        [TestMethod]
        public void GetParser_EmptyGcode_FallsBackToOrcaParser()
        {
            var parser = ParserFactory.GetParser(new ArgumentParser(["--default"]), _telemetry, _output, string.Empty);

            Assert.IsInstanceOfType<OrcaParser>(parser);
        }
    }
}
