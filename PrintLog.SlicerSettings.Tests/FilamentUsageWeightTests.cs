using PrintLog.SlicerSettings.BambuStudio;
using PrintLog.SlicerSettings.OrcaSlicer;
using PrintLog.SlicerSettings.PrusaSlicer;

namespace PrintLog.SlicerSettings.Tests
{
    /// <summary>
    /// Each filamentUsage entry carries the slot's weight as well as its length, so the new-print page shows grams.
    /// The UI ignores material_used_mg whenever filamentUsage is present.
    /// </summary>
    [TestClass]
    public class FilamentUsageWeightTests
    {
        [TestMethod]
        public void ShouldTakeEachSlotsGramsFromTheSlicer()
        {
            var gcode = TestData.Load(Path.Combine("OrcaSlicer", "orcaslicer-2.5.0-alpha-cube-20mm.gcode"));

            var settings = new OrcaParser("").ParseGcode(gcode).settings;

            // Orca's preview shows 4.00 g for this cube: "; filament used [g] = 4.00".
            var slot = settings.filamentUsage!.Single();
            Assert.AreEqual(4000, slot.EstimatedAmountMg);
            Assert.AreEqual(1.341, slot.EstimatedLengthInM);
            Assert.AreEqual(PrintFilamentSourceMeasurement.Length, slot.EstimatedSource);
        }

        [TestMethod]
        public void ShouldKeepEachSlotsOwnGramsWhenSeveralSlotsAreUsed()
        {
            var gcode = TestData.Load(Path.Combine("OrcaSlicer", "orcaslicer-2.2.0-rc-calibration-cube-two-filament.gcode"));

            var settings = new OrcaParser("").ParseGcode(gcode).settings;

            CollectionAssert.AreEqual(new double?[] { 4530, 5590 }, settings.filamentUsage!.Select(f => f.EstimatedAmountMg).ToList());
        }

        [TestMethod]
        public void ShouldSkipUnusedSlotsWithoutShiftingTheGrams()
        {
            var gcode = """
                ; generated by OrcaSlicer 2.5.0
                ; filament used [mm] = 1363.45, 0.00, 1612.57
                ; filament used [g] = 4.07, 0.00, 4.81
                """;

            var settings = new OrcaParser("").ParseGcode(gcode).settings;

            CollectionAssert.AreEqual(new double?[] { 4070, 4810 }, settings.filamentUsage!.Select(f => f.EstimatedAmountMg).ToList());
        }

        [TestMethod]
        public void ShouldReadBambuStudiosPerSlotWeightKey()
        {
            var gcode = TestData.Load(Path.Combine("BambuStudio", "bambustudio-01.10.01.50-calibration-cube-two-filament.gcode"));

            var settings = new BambuStudioParser("").ParseGcode(gcode).settings;

            // "; total filament weight [g] : 27.38,34.75"
            CollectionAssert.AreEqual(new double?[] { 27380, 34750 }, settings.filamentUsage!.Select(f => f.EstimatedAmountMg).ToList());
        }

        [TestMethod]
        public void ShouldWorkOutEachSlotsGramsFromItsLengthDiameterAndDensityWhenTheSlicerGivesNone()
        {
            var gcode = """
                ; generated by OrcaSlicer 2.5.0
                ; filament used [mm] = 1000, 500
                ; filament_diameter = 1.75,1.75
                ; filament_density = 1.24,1.27
                """;

            var settings = new OrcaParser("").ParseGcode(gcode).settings;

            // π × 0.875² mm² × 1000 mm × 1.24 mg/mm³ = 2982.6 mg; the second slot uses its own density.
            CollectionAssert.AreEqual(new double?[] { 2982, 1527 }, settings.filamentUsage!.Select(f => f.EstimatedAmountMg).ToList());
        }

        [TestMethod]
        public void ShouldLeaveTheGramsEmptyWhenNothingGivesAWeight()
        {
            var gcode = """
                ; generated by PrusaSlicer 2.9.2
                ; filament used [mm] = 1000
                """;

            var settings = new PrusaParser("").ParseGcode(gcode).settings;

            Assert.IsNull(settings.filamentUsage!.Single().EstimatedAmountMg);
        }

        [TestMethod]
        public void ShouldKeepMaterialUsedEmptyWhenThereIsAPerSlotBreakdown()
        {
            var gcode = TestData.Load(Path.Combine("OrcaSlicer", "orcaslicer-2.5.0-alpha-cube-20mm.gcode"));

            var settings = new OrcaParser("").ParseGcode(gcode).settings;

            // The UI reads material_used_mg only when there is no filamentUsage, so the total stays out of the payload.
            Assert.IsNull(settings.material_used_mg);
        }
    }
}
