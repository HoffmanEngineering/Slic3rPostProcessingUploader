using System.Diagnostics;
using System.Text;
using System.Text.Json.Nodes;
using PrintLog.SlicerSettings.Computed;

namespace PrintLog.SlicerSettings.Tests;

/// <summary>
/// The entry point for a server that has a whole (windowed) G-code file plus what a client measured and read on the
/// slicing machine: object bounds and the user's preset files. Each fixture is parsed both ways, the uploader's way
/// (toolpath scan, presets from a config root on disk) and through <see cref="SlicerGcodeParser"/> with the same
/// inputs in memory, and the settings JSON must be identical.
/// </summary>
[TestClass]
public sealed class SlicerGcodeParserTests
{
    private static readonly string PresetsRoot = TestData.FullPath("Presets");

    public static IEnumerable<object[]> FixturesAndTemplates =>
        new[] { "OrcaSlicer", "AnycubicSlicerNext", "BambuStudio", "PrusaSlicer", "FLSunSlicer" }
            .SelectMany(TestData.EnumerateFixtures)
            .SelectMany(path => new[] { "default", "full" }.Select(template => new object[] { path, template }));

    [TestMethod]
    [DynamicData(nameof(FixturesAndTemplates))]
    public void Parse_WithMeasuredModelsAndPresetFiles_MatchesTheUploader(string fixturePath, string template)
    {
        var expected = ParseLikeTheUploader(fixturePath, template, [PresetsRoot]);

        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixturePath), new SlicerGcodeOptions(template, ScanModels(fixturePath), ReadPresets(PresetsRoot)));

        Assert.AreEqual(expected.Slicer, result.Slicer);
        Assert.AreEqual(expected.CuraVersion, result.Version);
        Assert.AreEqual(SettingsJsonOf(expected), Compact(result.SettingsJson));
    }

    [TestMethod]
    [DynamicData(nameof(FixturesAndTemplates))]
    public void Parse_WithoutModelsOrPresets_MatchesTheUploaderWithNoConfigRootsAndNoModels(string fixturePath, string template)
    {
        var expected = ParseLikeTheUploader(fixturePath, template, [], dropModels: true);

        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixturePath), new SlicerGcodeOptions(template, [], []));

        Assert.AreEqual(SettingsJsonOf(expected), Compact(result.SettingsJson));
    }

    [TestMethod]
    public void Parse_OrcaBenchy_RendersTheSuppliedModels()
    {
        const string fixture = "OrcaSlicer/orcaslicer-2.4.0-benchy-x16.gcode";

        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixture), new SlicerGcodeOptions("default", ScanModels(fixture), []));

        StringAssert.Contains(Note(result), "Models:\n  3DBenchy.drc  ×16   55.6 × 30.9 × 48.0 mm\n");
    }

    [TestMethod]
    public void Parse_OrcaCube_ListsOnlyTheChangesTheSuppliedPresetsDoNotSave()
    {
        const string fixture = "OrcaSlicer/orcaslicer-2.2.0-rc-calibration-cube.gcode";

        var withPresets = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixture), new SlicerGcodeOptions("default", [], ReadPresets(PresetsRoot)));
        var withoutPresets = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixture), new SlicerGcodeOptions("default", [], []));

        // PLA.json saves nozzle_temperature; JGMaker R1.json saves a different printable_area.
        StringAssert.Contains(Note(withPresets), "Unsaved changes: nozzle_temperature_initial_layer = 205, printable_area = 0x0,230x0,230x230,0x230\n");
        StringAssert.Contains(Note(withoutPresets), "nozzle_temperature = 205, nozzle_temperature_initial_layer = 205, printable_area");
    }

    [TestMethod]
    public void Parse_ExtractsTheThumbnail()
    {
        const string fixture = "OrcaSlicer/orcaslicer-2.2.0-rc-calibration-cube.gcode";

        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixture), new SlicerGcodeOptions("default", [], []));

        Assert.IsFalse(string.IsNullOrEmpty((string?)Settings(result)["snapshot"]));
    }

    [TestMethod]
    public void Parse_UsesCamelCaseNamesLikeTheUploadersWireFormat()
    {
        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader("OrcaSlicer/orcaslicer-2.2.0-rc-calibration-cube-two-filament.gcode"), new SlicerGcodeOptions("default", [], []));

        var settings = Settings(result);
        Assert.IsNotNull(settings["note"]);
        Assert.IsNotNull(settings["estimated_print_time_seconds"]);
        Assert.IsNotNull(settings["filamentUsage"]?[0]?["estimatedLengthInM"]);
        Assert.IsTrue(settings.ContainsKey("print_name"));
        Assert.IsTrue(settings.ContainsKey("file_name"));
    }

    [TestMethod]
    [DataRow("default")]
    [DataRow("full")]
    [DataRow("Default")]
    [DataRow("FULL")]
    public void Parse_AcceptsTheBuiltInTemplatesInAnyCase(string template)
    {
        var result = SlicerGcodeParser.Parse("; generated by OrcaSlicer 2.4.0 on 2026-01-01 at 10:00:00\n", new SlicerGcodeOptions(template, [], []));

        Assert.AreEqual("2.4.0", result.Version);
    }

    [TestMethod]
    [DataRow("custom")]
    [DataRow("")]
    [DataRow(" default")]
    [DataRow(null)]
    public void Parse_RejectsAnyOtherTemplate(string? template)
    {
        Assert.ThrowsException<ArgumentException>(() => SlicerGcodeParser.Parse("", new SlicerGcodeOptions(template!, [], [])), template ?? "null");
    }

    [TestMethod]
    public void Parse_RejectsNullArguments()
    {
        Assert.ThrowsException<ArgumentNullException>(() => SlicerGcodeParser.Parse(null!, new SlicerGcodeOptions("default", [], [])));
        Assert.ThrowsException<ArgumentNullException>(() => SlicerGcodeParser.Parse("", null!));
    }

    [TestMethod]
    public void Parse_TreatsNullListsAsEmpty()
    {
        const string fixture = "OrcaSlicer/orcaslicer-2.4.0-benchy-x16.gcode";

        var result = SlicerGcodeParser.Parse(ReadLikeTheUploader(fixture), new SlicerGcodeOptions("default", null!, null!));

        Assert.AreEqual(SettingsJsonOf(ParseLikeTheUploader(fixture, "default", [], dropModels: true)), Compact(result.SettingsJson));
    }

    [TestMethod]
    [DataRow(@"C:\Users\me\Prints\benchy_final.gcode", "benchy_final.gcode", "Benchy Final")]
    [DataRow("/home/me/prints/calibration_cube.gcode", "calibration_cube.gcode", "Calibration Cube")]
    [DataRow("cube.bgcode", "cube.bgcode", "Cube")]
    [DataRow("MyPart_gcode.gcode", "MyPart_gcode.gcode", "My Part")]
    public void Parse_WithOutputName_SetsTheFileAndPrintNameLikeTheUploader(string outputName, string fileName, string printName)
    {
        var result = SlicerGcodeParser.Parse("", new SlicerGcodeOptions("default", [], []) { OutputName = outputName });

        Assert.AreEqual(fileName, (string?)Settings(result)["file_name"]);
        Assert.AreEqual(printName, (string?)Settings(result)["print_name"]);
    }

    [TestMethod]
    public void Parse_WithoutOutputName_LeavesTheFileAndPrintNameNull()
    {
        var settings = Settings(SlicerGcodeParser.Parse("", new SlicerGcodeOptions("default", [], [])));

        Assert.IsNull(settings["file_name"]);
        Assert.IsNull(settings["print_name"]);
    }

    [TestMethod]
    [DataRow("")]
    [DataRow("; nothing to see here\n")]
    [DataRow("; thumbnail begin 99999999999x1 5\n; x\n; thumbnail end\n")]
    [DataRow("; estimated printing time (normal mode) = 99999999d\n")]
    [DataRow("; filament used [g] = 1e300\n")]
    [DataRow("; filament used [mm] = Infinity, NaN, 1e400\n; filament_diameter = 1.75\n; filament_density = 1.24\n")]
    [DataRow("; different_settings_to_system = a;b\n; inherits_group = \"x\";\"y\";\"z\"\n; print_settings_id = ../../etc\n")]
    public void Parse_MalformedText_DoesNotThrow(string gcode)
    {
        var result = SlicerGcodeParser.Parse(
            gcode,
            new SlicerGcodeOptions("full", [new ModelBounds("Cube", double.NaN, 1, 2, 3, double.PositiveInfinity)], [new UserPresetFile("process", "../../etc", "{ not json")]));

        Assert.AreEqual("Unknown", result.Version);
        Assert.IsNotNull(JsonNode.Parse(result.SettingsJson));
    }

    [TestMethod]
    public void Parse_LoneSurrogatesInSuppliedText_StillGiveAResult()
    {
        // JSON can carry "\uD800" on its own, so a model name or output name may hold half a character.
        var result = SlicerGcodeParser.Parse(
            "; generated by OrcaSlicer 2.4.0 on 2026-01-01\n",
            new SlicerGcodeOptions("default", [new ModelBounds("a\uD800b", 0, 1, 0, 1, 1)], []) { OutputName = new string('x', 99) + "😀\uDC00.gcode" });

        Assert.AreEqual("OrcaSlicer", result.Slicer);
        StringAssert.Contains(Note(result), "Models:");
        Assert.IsNotNull((string?)Settings(result)["print_name"]);
    }

    [TestMethod]
    public void Parse_ThrowingDebugLog_IsSwallowed()
    {
        // The preset is missing, which the locator reports through the debug log.
        const string gcode = "; generated by OrcaSlicer 2.4.0 on 2026-01-01\n; different_settings_to_system = wall_loops;;\n; inherits_group = \"P0\";;\n; print_settings_id = P\n; wall_loops = 3\n";

        var result = SlicerGcodeParser.Parse(gcode, new SlicerGcodeOptions("default", [], []) { DebugLog = _ => throw new InvalidOperationException("log is down") });

        StringAssert.Contains(Note(result), "wall_loops = 3");
    }

    [TestMethod]
    [Timeout(30_000)]
    public void Parse_HostileModels_AreBoundedAndLinear()
    {
        // About what fits in the API's 1 MB metadata cap: many distinct sizes and one enormous name.
        var models = Enumerable.Range(0, 20_000).Select(i => new ModelBounds("m" + i, 0, i, 0, i, i)).Prepend(new ModelBounds(new string('x', 1_000_000), 0, 1, 0, 1, 1)).ToList();
        const string gcode = "; generated by OrcaSlicer 2.4.0 on 2026-01-01\n";

        SlicerGcodeParser.Parse(gcode, new SlicerGcodeOptions("default", models, []));
        var stopwatch = Stopwatch.StartNew();
        var result = SlicerGcodeParser.Parse(gcode, new SlicerGcodeOptions("default", models, []));
        stopwatch.Stop();

        var note = Note(result);
        Assert.IsTrue(stopwatch.Elapsed < TimeSpan.FromSeconds(2), $"{stopwatch.ElapsedMilliseconds} ms");
        Assert.AreEqual(SlicerGcodeParser.MaxModels - 1, note.Split('\n').Count(line => line.StartsWith("  m", StringComparison.Ordinal)), "the long name is kept, the rest is cut at the cap");
        Assert.IsTrue(note.Length < 1_000_000, $"{note.Length} chars");
    }

    [TestMethod]
    public void Parse_LongModelNames_AreTruncated()
    {
        var name = new string('x', SlicerGcodeParser.MaxModelNameLength + 10);

        var result = SlicerGcodeParser.Parse("; generated by OrcaSlicer 2.4.0 on 2026-01-01\n", new SlicerGcodeOptions("default", [new ModelBounds(name, 0, 1, 0, 1, 1)], []));

        StringAssert.Contains(Note(result), "  " + name[..SlicerGcodeParser.MaxModelNameLength] + "  ×1");
        Assert.IsFalse(Note(result).Contains(name, StringComparison.Ordinal));
    }

    [TestMethod]
    [Timeout(30_000)]
    [DataRow("; thumbnail begin 1x1 5\n", "unterminated thumbnails")]
    [DataRow("; generated by OrcaSlicer x ", "a version marker with no ' on', on one line")]
    [DataRow("; a = b = c = d = e = f = g = h ", "one long setting line full of separators")]
    public void Parse_HostileInput_IsLinear(string repeated, string description)
    {
        var text = new StringBuilder().Insert(0, repeated, 2_000_000 / repeated.Length).ToString();
        var options = new SlicerGcodeOptions("full", [], []);

        SlicerGcodeParser.Parse(text, options);
        var stopwatch = Stopwatch.StartNew();
        SlicerGcodeParser.Parse(text, options);
        stopwatch.Stop();

        Assert.IsTrue(stopwatch.Elapsed < TimeSpan.FromSeconds(2), $"{description}: {stopwatch.ElapsedMilliseconds} ms");
    }

    /// <summary>What <c>Program.cs</c> reads: binary G-code decoded, text files windowed.</summary>
    private static string ReadLikeTheUploader(string fixturePath)
    {
        var path = TestData.FullPath(fixturePath);
        return BinaryGcode.IsBinaryGcodeFile(path) ? BinaryGcode.ReadFromFile(path) : GcodeWindow.ReadFromFile(path);
    }

    /// <summary>
    /// The uploader's parse (<c>ParserFactory</c> with <c>--default</c> or <c>--full</c>, then <c>ParseGcode</c> with
    /// the real file and config roots). <paramref name="dropModels"/> removes <c>{{models}}</c> from the template, for
    /// comparing with a parse that was given no measurements.
    /// </summary>
    private static CuraSettingDto ParseLikeTheUploader(string fixturePath, string template, string[] configRoots, bool dropModels = false)
    {
        var path = TestData.FullPath(fixturePath);
        var text = ReadLikeTheUploader(fixturePath);
        var slicer = SlicerDetector.Detect(text);
        var noteTemplate = (template == "full" ? slicer.FullTemplate : slicer.DefaultTemplate).getNoteTemplate();
        if (dropModels)
        {
            noteTemplate = noteTemplate.Replace("{{models}}\n", string.Empty, StringComparison.Ordinal);
        }

        var options = new ParseOptions(() => File.OpenRead(path), _ => { }, () => configRoots);
        return slicer.CreateParser(noteTemplate).ParseGcode(text, options);
    }

    /// <summary>What the plugin sends as <c>models</c>: the scanner's raw centerline bounds over the whole file.</summary>
    private static List<ModelBounds> ScanModels(string fixturePath)
    {
        using var stream = File.OpenRead(TestData.FullPath(fixturePath));
        return ObjectBoundsScanner.Scan(stream, _ => { })
            .Select(b => new ModelBounds(b.Name, b.MinX, b.MaxX, b.MinY, b.MaxY, b.MaxZ))
            .ToList();
    }

    /// <summary>What the plugin sends as <c>userPresets</c>: every preset file under the config root's accounts.</summary>
    private static List<UserPresetFile> ReadPresets(string configRoot) =>
        Directory.EnumerateFiles(Path.Combine(configRoot, "user"), "*.json", SearchOption.AllDirectories)
            .Select(file => new UserPresetFile(Path.GetFileName(Path.GetDirectoryName(file)!), Path.GetFileNameWithoutExtension(file), File.ReadAllText(file)))
            .ToList();

    /// <summary>The <c>settings</c> object of the uploader's request body, compacted.</summary>
    private static string SettingsJsonOf(CuraSettingDto dto) => JsonNode.Parse(dto.ToJSON())!["settings"]!.ToJsonString();

    private static string Compact(string json) => JsonNode.Parse(json)!.ToJsonString();

    private static JsonObject Settings(SlicerGcodeResult result) => JsonNode.Parse(result.SettingsJson)!.AsObject();

    private static string Note(SlicerGcodeResult result) => (string)Settings(result)["note"]!;
}
