using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;
using PrintLog.SlicerSettings.AnycubicSlicerNext;
using PrintLog.SlicerSettings.BambuStudio;
using PrintLog.SlicerSettings.FLSunSlicer;
using PrintLog.SlicerSettings.OrcaSlicer;
using PrintLog.SlicerSettings.PrusaSlicer;

namespace PrintLog.SlicerSettings.Tests;

/// <summary>
/// Whole-file parsing (the uploader's path, and what <see cref="SlicerConfigParser"/> builds on) on text crafted to
/// make a backtracking search quadratic, or to overflow a number. None of it may throw or take long.
/// </summary>
[TestClass]
public sealed class HostileInputTests
{
    private static readonly Func<IGcodeParser>[] Parsers =
    [
        () => new OrcaParser(null),
        () => new PrusaParser(null),
        () => new FLSunParser(null),
        () => new BambuStudioParser(null),
        () => new AnycubicSlicerNextParser(null),
    ];

    /// <summary>The regex <see cref="ThumbnailScanner"/> replaced, kept here as the oracle for its results.</summary>
    private static readonly Regex LegacyThumbnailRegex = new(
        "thumbnail(?:_JPG)? begin (\\d+)x(\\d+)[\\sa-zA-Z\\d]*([\\S\\s]*?); thumbnail end",
        RegexOptions.IgnoreCase | RegexOptions.Multiline);

    [TestMethod]
    [Timeout(60_000)]
    [DataRow("; thumbnail begin 1x1 5\n")]
    [DataRow("; thumbnail_JPG begin 1x1 5\n")]
    [DataRow("; generated by OrcaSlicer x ")]
    [DataRow("; generated by PrusaSlicer x ")]
    [DataRow("; generated by FlsunSlicer x ")]
    [DataRow("; generated by AnycubicSlicerNext x ")]
    [DataRow("; BambuStudio ")]
    [DataRow("; total estimated time: 1")]
    public void ParseGcode_HostileInput_IsLinear(string repeated)
    {
        // About 1 MB. Before the fix the first row took 43 s and the marker rows grew the same way.
        var text = new StringBuilder().Insert(0, repeated, 1_000_000 / repeated.Length).ToString();

        foreach (var create in Parsers)
        {
            var parser = create();
            var stopwatch = Stopwatch.StartNew();
            parser.ParseGcode(text);
            stopwatch.Stop();

            Assert.IsTrue(stopwatch.Elapsed < TimeSpan.FromSeconds(1), $"{parser.GetType().Name}: {stopwatch.ElapsedMilliseconds} ms");
        }
    }

    [TestMethod]
    [DataRow("; thumbnail begin 99999999999x1 5\n; x\n; thumbnail end\n")]
    [DataRow("; thumbnail begin 2147483647x2147483647 5\n; x\n; thumbnail end\n")]
    [DataRow("; thumbnail begin ١٢x٣ 5\n; x\n; thumbnail end\n")]
    [DataRow("; estimated printing time (normal mode) = 99999999d\n")]
    [DataRow("; filament used [g] = 1e300\n")]
    [DataRow("; filament used [mm] = Infinity, NaN, 1e400\n; filament_diameter = 1.75\n; filament_density = 1.24\n")]
    public void ParseGcode_OutOfRangeNumbers_DoNotThrowOrWrap(string gcode)
    {
        foreach (var create in Parsers)
        {
            var result = create().ParseGcode(gcode);

            Assert.IsTrue(result.settings.estimated_print_time_seconds >= 0);
            Assert.IsTrue(result.settings.material_used_mg is null or >= 0, $"{result.settings.material_used_mg}");
            Assert.IsTrue((result.settings.filamentUsage ?? []).All(f => f.EstimatedLengthInM is { } m && double.IsFinite(m)));
        }
    }

    [TestMethod]
    public void ParseGcode_OversizedThumbnail_IsSkippedForAUsableOne()
    {
        var gcode = "; thumbnail begin 99999999999x1 5\n; AAAA\n; thumbnail end\n; thumbnail begin 16x16 5\n; BBBB\n; thumbnail end\n";

        var result = new OrcaParser(null).ParseGcode(gcode);

        Assert.AreEqual("BBBB", result.settings.Snapshot);
    }

    [TestMethod]
    public void ParseAsSeconds_DaysThatOverflowAnInt_IsNull()
    {
        var parser = new OrcaParser(null);

        Assert.IsNull(parser.ParseAsSeconds("99999999d"));
        Assert.IsNull(parser.ParseAsSeconds("-5m"));
        Assert.AreEqual(int.MaxValue, parser.ParseAsSeconds("2147483647s"));
    }

    public static IEnumerable<object[]> ThumbnailTexts()
    {
        foreach (var slicer in new[] { "OrcaSlicer", "PrusaSlicer", "BambuStudio", "FLSunSlicer", "AnycubicSlicerNext" })
        {
            foreach (var fixture in TestData.EnumerateFixtures(slicer))
            {
                yield return [fixture, TestData.Load(fixture)];
            }
        }

        yield return ["jpg then png", "; thumbnail_JPG begin 4x4 3\n; AAA\n; thumbnail_JPG end\n; thumbnail begin 8x8 3\n; BBB\n; thumbnail end\n"];
        yield return ["case", "; THUMBNAIL BEGIN 4X4 3\n; AAA\n; Thumbnail End\n"];
        yield return ["qoi is not a match", "; thumbnail_QOI begin 4x4 3\n; AAA\n; thumbnail_QOI end\n; thumbnail begin 2x2 1\n; B\n; thumbnail end\n"];
        yield return ["unterminated then terminated", "; thumbnail begin 1x1 5\n; thumbnail begin 2x2 5\n; CC\n; thumbnail end\n"];
        yield return ["terminated then unterminated", "; thumbnail begin 2x2 5\n; CC\n; thumbnail end\n; thumbnail begin 1x1 5\n; DD\n"];
        yield return ["no digits", "; thumbnail begin x2 5\n; thumbnail begin 3x 5\n; thumbnail begin 3x3\n; E\n; thumbnail end"];
        yield return ["thumbnail word inside", "; thumbnailthumbnail begin 5x5 abc 12 \n\n; F\n; thumbnail end"];
        yield return ["payload starting with letters", "; thumbnail begin 5x5 1\niVBOR\n; +G==\n; thumbnail end"];
        yield return ["empty", string.Empty];
    }

    [TestMethod]
    [DynamicData(nameof(ThumbnailTexts), DynamicDataSourceType.Method)]
    public void ThumbnailScanner_FindsWhatTheLegacyRegexMatched(string name, string text)
    {
        var expected = LegacyThumbnailRegex.Matches(text)
            .Select(m => new ThumbnailScanner.Block(m.Groups[1].Value, m.Groups[2].Value, m.Groups[3].Value))
            .ToList();

        var actual = ThumbnailScanner.Find(text);

        CollectionAssert.AreEqual(expected, actual, name);
    }
}
